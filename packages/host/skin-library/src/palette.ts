/** Built-in skin ids; an imported pack may not reuse one. */
export const BUILTIN_SKIN_IDS: ReadonlySet<string> = new Set(BUILTIN_SKINS.map(skin => skin.id))

/**
 * Look up one built-in skin.
 * @param id - candidate skin id.
 * @returns the built-in skin, or `undefined` when `id` names none.
 */
export function builtinSkin(id: string): SkinDefinition | undefined {
  return BUILTIN_SKINS.find(skin => skin.id === id)
}
