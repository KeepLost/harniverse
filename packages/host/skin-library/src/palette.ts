/** A soft light spot fading to transparent. */
function glow(at: readonly [x: number, y: number], size: number, color: string, end: number): SkinGradientLayer {
  return { type: 'radial', at, size, stops: [[color, 0], ['transparent', end]] }
}

/** The three-stop base wash beneath the glows. */
function wash(angle: number, from: string, middle: string, to: string): SkinGradientLayer {
  return { type: 'linear', angle, stops: [[from, 0], [middle, 55], [to, 100]] }
}

