export type ShellCopy = typeof en

/**
 * Pick shell copy by an Electron `app.getLocale()` or `navigator.language` value.
 * @param locale - the observed locale string, or undefined when unavailable.
 * @returns the English table unless the locale selects Chinese.
 */
export function shellCopy(locale: string | undefined): ShellCopy {
  return locale !== undefined && locale.toLowerCase().startsWith('zh') ? zh : en
}
